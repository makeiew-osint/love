const grid = document.querySelector('#reason-grid');
const openedCount = document.querySelector('#opened-count');
const progressBar = document.querySelector('#progress-bar');
const openAll = document.querySelector('#open-all');
const opened = new Set();

reasons.forEach((reason, index) => {
  const card = document.createElement('button');
  card.type = 'button';
  card.className = 'reason-card';
  card.setAttribute('aria-label', `Причина ${index + 1}`);
  card.innerHTML = `<span class="reason-number">${String(index + 1).padStart(2, '0')}</span><span class="reason-cover">нажми, чтобы открыть ♡</span><span class="reason-text">${reason}</span>`;
  card.addEventListener('click', () => {
    card.classList.toggle('open');
    if (card.classList.contains('open')) opened.add(index);
    else opened.delete(index);
    updateProgress();
  });
  grid.append(card);
});

function updateProgress() {
  openedCount.textContent = opened.size;
  progressBar.style.transform = `scaleX(${opened.size / reasons.length})`;
}

openAll.addEventListener('click', () => {
  const first = grid.firstElementChild;
  first.classList.add('open');
  opened.add(0);
  updateProgress();
  first.scrollIntoView({ behavior: 'smooth', block: 'center' });
});
